"""Hierarchical SAC/CTDE trainer for SAFE-PB V17.

V17 replaces V15's transition-level risk proxy and raw-action fairness
proxy with episode-level objectives computed from completed physical
trajectories. Daily weighted social loss drives a Rockafellar-Uryasev
CVaR terminal penalty; fairness is the variance of normalized daily
household discomfort. The ordinary SAC gradient step then learns from
those shaped episodic returns. Household actions still use the sequential
utility-price -> household-response API, and actor updates follow the
configured K-step alternating schedule.

This module implements the training mechanics; manuscript values must come
from held-out evaluation generated by scripts/run_v17_experiments.py.
"""
from __future__ import annotations
from dataclasses import dataclass
import numpy as np
import torch
import torch.nn.functional as F

from .sac_networks import GaussianActor, TwinCritic, soft_update, hard_update
from .environment import SafePBEnv
from .episode_metrics import summarize_episode


@dataclass
class SACConfig:
    gamma: float = 0.99
    tau: float = 0.005
    lr: float = 3e-4
    hidden: int = 64
    critic_hidden: int = 128
    batch_size: int = 32
    replay_capacity: int = 5000
    alternating_k: int = 24        # ENV STEPS per actor before switching -- now actually used
    target_entropy_scale: float = 1.0
    cvar_alpha: float = 0.90
    beta_r: float = 0.0            # complete-day CVaR weight (0 = disabled)
    beta_f: float = 0.0            # normalized-discomfort variance weight
    cvar_zeta_lr: float = 0.05
    risk_warmup_episodes: int = 20
    seed: int = 0


class ReplayBuffer:
    """Stores (u_obs, h_obs, u_act, h_act, reward, next_u_obs, next_h_obs, done)."""

    def __init__(self, capacity: int, u_obs_dim: int, h_obs_dim: int, n_households: int,
                 u_act_dim: int, h_act_dim: int, seed: int = 0):
        self.capacity = capacity
        self.u_obs = np.zeros((capacity, u_obs_dim), dtype=np.float32)
        self.h_obs = np.zeros((capacity, n_households, h_obs_dim), dtype=np.float32)
        self.u_act = np.zeros((capacity, u_act_dim), dtype=np.float32)
        self.h_act = np.zeros((capacity, n_households, h_act_dim), dtype=np.float32)
        self.reward = np.zeros(capacity, dtype=np.float32)
        self.next_u_obs = np.zeros((capacity, u_obs_dim), dtype=np.float32)
        self.next_h_obs = np.zeros((capacity, n_households, h_obs_dim), dtype=np.float32)
        self.done = np.zeros(capacity, dtype=np.float32)
        self.ptr, self.size = 0, 0
        self.rng = np.random.default_rng(seed)

    def add(self, u_obs, h_obs, u_act, h_act, reward, next_u_obs, next_h_obs, done):
        i = self.ptr
        self.u_obs[i], self.h_obs[i] = u_obs, h_obs
        self.u_act[i], self.h_act[i] = u_act, h_act
        self.reward[i] = reward
        self.next_u_obs[i], self.next_h_obs[i] = next_u_obs, next_h_obs
        self.done[i] = float(done)
        self.ptr = (self.ptr + 1) % self.capacity
        self.size = min(self.size + 1, self.capacity)

    def sample(self, batch_size: int):
        idx = self.rng.integers(0, self.size, size=min(batch_size, self.size))
        return (self.u_obs[idx], self.h_obs[idx], self.u_act[idx], self.h_act[idx],
                self.reward[idx], self.next_u_obs[idx], self.next_h_obs[idx], self.done[idx])

    def state_dict(self) -> dict:
        return {"u_obs": self.u_obs, "h_obs": self.h_obs, "u_act": self.u_act, "h_act": self.h_act,
                "reward": self.reward, "next_u_obs": self.next_u_obs, "next_h_obs": self.next_h_obs,
                "done": self.done, "ptr": self.ptr, "size": self.size,
                "rng_state": self.rng.bit_generator.state}

    def load_state_dict(self, d: dict):
        self.u_obs, self.h_obs = d["u_obs"], d["h_obs"]
        self.u_act, self.h_act = d["u_act"], d["h_act"]
        self.reward = d["reward"]
        self.next_u_obs, self.next_h_obs = d["next_u_obs"], d["next_h_obs"]
        self.done = d["done"]
        self.ptr, self.size = d["ptr"], d["size"]
        self.rng.bit_generator.state = d["rng_state"]

    def __len__(self):
        return self.size


class HierarchicalSACTrainer:
    def __init__(self, env: SafePBEnv, cfg: SACConfig | None = None):
        self.env = env
        self.cfg = cfg = cfg or SACConfig()
        torch.manual_seed(cfg.seed)

        n_h = env.n_households
        u_obs_dim, u_act_dim = env.cfg.n_utility_obs, env.cfg.n_utility_act
        h_obs_dim, h_act_dim = env.cfg.n_household_obs, env.cfg.n_household_act
        global_obs_dim = u_obs_dim + n_h * h_obs_dim
        global_act_dim = u_act_dim + n_h * h_act_dim

        self.utility_actor = GaussianActor(u_obs_dim, u_act_dim, cfg.hidden)
        self.household_actor = GaussianActor(h_obs_dim, h_act_dim, cfg.hidden)  # parameter-shared
        self.critic = TwinCritic(global_obs_dim, global_act_dim, cfg.critic_hidden)
        self.critic_target = TwinCritic(global_obs_dim, global_act_dim, cfg.critic_hidden)
        hard_update(self.critic_target, self.critic)

        self.utility_opt = torch.optim.Adam(self.utility_actor.parameters(), lr=cfg.lr)
        self.household_opt = torch.optim.Adam(self.household_actor.parameters(), lr=cfg.lr)
        self.critic_opt = torch.optim.Adam(self.critic.parameters(), lr=cfg.lr)

        self.log_alpha_u = torch.zeros(1, requires_grad=True)
        self.log_alpha_h = torch.zeros(1, requires_grad=True)
        self.alpha_opt = torch.optim.Adam([self.log_alpha_u, self.log_alpha_h], lr=cfg.lr)
        self.target_entropy_u = -u_act_dim * cfg.target_entropy_scale
        # CORRECTED: household log-probs are SUMMED across all n_h households
        # before use (see train_step), so the target entropy for that summed
        # quantity must scale with the JOINT action dimension, not a single
        # household's. An earlier version used -h_act_dim (=-1) here, 10x
        # too small in magnitude for this scenario's 10 households.
        self.target_entropy_h = -(n_h * h_act_dim) * cfg.target_entropy_scale

        # Complete-day CVaR state.  Unlike V15's transition-level critic
        # proxy, this scalar is updated from actually completed daily losses.
        self.cvar_zeta = None
        self.daily_loss_history = []

        self.buffer = ReplayBuffer(cfg.replay_capacity, u_obs_dim, h_obs_dim, n_h,
                                    u_act_dim, h_act_dim, seed=cfg.seed)
        self.n_households = n_h
        self.episode_losses = []  # kept for logging/diagnostics only now, not for CVaR gradients
        self.train_step_count = 0
        self.env_step_count = 0  # drives the alternating_k schedule

    def should_update_utility(self) -> bool:
        """K-step alternating schedule, actually using alternating_k now:
        True for the first `alternating_k` env steps, False for the next
        `alternating_k`, repeating."""
        block = self.env_step_count // self.cfg.alternating_k
        return (block % 2) == 0

    def collect_episode(self, deterministic: bool = False):
        """Collect one complete day, then attach the *daily* CVaR/fairness
        penalty to the terminal transition before storing the trajectory.

        This makes the replayed return correspond to an episodic objective:
        base weighted social loss + beta_r*CVaR_alpha(daily loss) +
        beta_f*Var(normalized daily household discomfort).  No transition-
        level risk or raw-action fairness proxy is used.
        """
        u_obs, h_obs = self.env.reset()
        transitions=[]; infos=[]; base_total_reward=0.0; done=False
        while not done:
            u_t = torch.as_tensor(u_obs, dtype=torch.float32).unsqueeze(0)
            with torch.no_grad():
                u_act, _, _ = self.utility_actor.sample(u_t, deterministic=deterministic)
            u_act_np = u_act.squeeze(0).numpy()
            h_obs_current = self.env.utility_announce_price(u_act_np)
            h_t = torch.as_tensor(h_obs_current, dtype=torch.float32)
            with torch.no_grad():
                h_act, _, _ = self.household_actor.sample(h_t, deterministic=deterministic)
            h_act_np = h_act.numpy()
            next_u_obs, next_h_obs, reward, done, info = self.env.household_step(h_act_np)
            transitions.append([u_obs, h_obs_current, u_act_np, h_act_np, reward,
                                next_u_obs, next_h_obs, done])
            base_total_reward += reward; infos.append(info)
            u_obs, h_obs = next_u_obs, next_h_obs
            self.env_step_count += 1

        metrics = summarize_episode(infos, self.env.scenario)
        daily_loss = float(metrics['weighted_social_loss'])
        fairness = float(metrics['normalized_discomfort_variance'])
        self.daily_loss_history.append(daily_loss)

        # Rockafellar-Uryasev stochastic VaR threshold update. Warm up with
        # empirical daily losses before applying a tail penalty.
        if self.cvar_zeta is None and len(self.daily_loss_history) >= self.cfg.risk_warmup_episodes:
            self.cvar_zeta = float(np.quantile(self.daily_loss_history, self.cfg.cvar_alpha))
        risk_excess = 0.0
        if self.cvar_zeta is not None:
            z=float(self.cvar_zeta)
            risk_excess=max(daily_loss-z, 0.0)/(1.0-self.cfg.cvar_alpha)
            indicator = 1.0 if daily_loss > z else 0.0
            grad = 1.0 - indicator/(1.0-self.cfg.cvar_alpha)
            self.cvar_zeta = z - self.cfg.cvar_zeta_lr*grad

        # Environment reward is scaled by 1/1000, so apply objective terms
        # in the same scale at the terminal transition. The zeta constant is
        # omitted from policy reward because it does not depend on actions.
        risk_component = self.cfg.beta_r * risk_excess
        fairness_component = self.cfg.beta_f * fairness
        terminal_penalty = (risk_component + fairness_component) / 1000.0
        transitions[-1][4] = float(transitions[-1][4] - terminal_penalty)
        for tr in transitions:
            self.buffer.add(*tr)
        shaped_total_reward = base_total_reward - terminal_penalty
        self.episode_losses.append(-shaped_total_reward)
        metrics.update({'base_total_reward': float(base_total_reward),
                        'shaped_total_reward': float(shaped_total_reward),
                        'cvar_zeta': None if self.cvar_zeta is None else float(self.cvar_zeta),
                        'risk_excess_penalty_unweighted': float(risk_excess),
                        'fairness_penalty_unweighted': fairness,
                        'risk_objective_component': float(risk_component),
                        'fairness_objective_component': float(fairness_component),
                        'risk_component_fraction_of_daily_loss': float(
                            abs(risk_component) / max(abs(daily_loss), 1e-12)),
                        'fairness_component_fraction_of_daily_loss': float(
                            abs(fairness_component) / max(abs(daily_loss), 1e-12))})
        self.last_episode_metrics = metrics
        return shaped_total_reward, infos

    def evaluate_episode(self, deterministic: bool = True):
        """Run a held-out day without replay insertion, learning, or reward
        shaping. Returns only measurements produced by the executed policy."""
        u_obs, _ = self.env.reset(); infos=[]; done=False
        while not done:
            with torch.no_grad():
                u_act,_,_=self.utility_actor.sample(torch.as_tensor(u_obs,dtype=torch.float32).unsqueeze(0),
                                                    deterministic=deterministic)
            h_obs=self.env.utility_announce_price(u_act.squeeze(0).numpy())
            with torch.no_grad():
                h_act,_,_=self.household_actor.sample(torch.as_tensor(h_obs,dtype=torch.float32),
                                                       deterministic=deterministic)
            u_obs,_,_,done,info=self.env.household_step(h_act.numpy())
            infos.append(info)
        return summarize_episode(infos, self.env.scenario), infos

    def train_step(self):
        """ONE gradient step. Which actor updates is now decided
        INTERNALLY via `should_update_utility()` (the alternating_k
        schedule), not passed in by the caller -- an earlier version let
        the caller alternate arbitrarily (the demo script alternated every
        EPISODE, ignoring alternating_k entirely)."""
        if len(self.buffer) < self.cfg.batch_size:
            raise RuntimeError(f"replay buffer has only {len(self.buffer)} transitions, "
                                f"need >= {self.cfg.batch_size} before training")
        cfg = self.cfg
        update_utility = self.should_update_utility()
        (u_obs, h_obs, u_act, h_act, reward, next_u_obs, next_h_obs, done) = self.buffer.sample(cfg.batch_size)
        u_obs_t = torch.as_tensor(u_obs, dtype=torch.float32)
        h_obs_t = torch.as_tensor(h_obs, dtype=torch.float32)
        u_act_t = torch.as_tensor(u_act, dtype=torch.float32)
        h_act_t = torch.as_tensor(h_act, dtype=torch.float32)
        reward_t = torch.as_tensor(reward, dtype=torch.float32)
        next_u_obs_t = torch.as_tensor(next_u_obs, dtype=torch.float32)
        next_h_obs_t = torch.as_tensor(next_h_obs, dtype=torch.float32)
        done_t = torch.as_tensor(done, dtype=torch.float32)
        B = u_obs_t.shape[0]

        global_obs = torch.cat([u_obs_t, h_obs_t.reshape(B, -1)], dim=-1)
        global_act = torch.cat([u_act_t, h_act_t.reshape(B, -1)], dim=-1)
        next_global_obs = torch.cat([next_u_obs_t, next_h_obs_t.reshape(B, -1)], dim=-1)

        alpha_u = self.log_alpha_u.exp().detach()
        alpha_h = self.log_alpha_h.exp().detach()

        # ---- Critic update (always happens) ----
        with torch.no_grad():
            next_u_act, next_u_logp, _ = self.utility_actor.sample(next_u_obs_t)
            n_h = self.n_households
            next_h_act_flat = torch.zeros(B, n_h, h_act_t.shape[-1])
            next_h_logp_sum = torch.zeros(B)
            for i in range(n_h):
                a, lp, _ = self.household_actor.sample(next_h_obs_t[:, i, :])
                next_h_act_flat[:, i, :] = a
                next_h_logp_sum += lp
            next_global_act = torch.cat([next_u_act, next_h_act_flat.reshape(B, -1)], dim=-1)
            q1_next, q2_next = self.critic_target(next_global_obs, next_global_act)
            q_next = torch.min(q1_next, q2_next) - alpha_u * next_u_logp - alpha_h * next_h_logp_sum
            target_q = reward_t + cfg.gamma * (1 - done_t) * q_next

        q1, q2 = self.critic(global_obs, global_act)
        critic_loss = F.mse_loss(q1, target_q) + F.mse_loss(q2, target_q)
        self.critic_opt.zero_grad()
        critic_loss.backward()
        self.critic_opt.step()
        soft_update(self.critic_target, self.critic, cfg.tau)

        losses = {"critic_loss": float(critic_loss.item()), "updated": "utility" if update_utility else "household"}

        if update_utility:
            u_act_new, u_logp, _ = self.utility_actor.sample(u_obs_t)
            h_act_frozen = h_act_t
            global_act_pi = torch.cat([u_act_new, h_act_frozen.reshape(B, -1)], dim=-1)
            q1_pi, q2_pi = self.critic(global_obs, global_act_pi)
            q_pi = torch.min(q1_pi, q2_pi)
            actor_loss = (alpha_u * u_logp - q_pi).mean()

            # Risk is now represented by a real complete-day terminal
            # penalty inserted during collection, so ordinary SAC policy
            # improvement on replayed returns is sufficient here.
            total_actor_loss = actor_loss
            self.utility_opt.zero_grad()
            total_actor_loss.backward()
            self.utility_opt.step()

            alpha_loss = -(self.log_alpha_u * (u_logp.detach() + self.target_entropy_u)).mean()
            self.alpha_opt.zero_grad()
            alpha_loss.backward()
            self.alpha_opt.step()

            losses.update({"utility_actor_loss": float(actor_loss.item()),
                            "utility_alpha_loss": float(alpha_loss.item())})
        else:
            h_act_new = torch.zeros(B, self.n_households, h_act_t.shape[-1])
            h_logp_sum = torch.zeros(B)
            for i in range(self.n_households):
                a, lp, _ = self.household_actor.sample(h_obs_t[:, i, :])
                h_act_new[:, i, :] = a
                h_logp_sum += lp
            global_act_pi = torch.cat([u_act_t, h_act_new.reshape(B, -1)], dim=-1)
            q1_pi, q2_pi = self.critic(global_obs, global_act_pi)
            q_pi = torch.min(q1_pi, q2_pi)

            # Fairness is now the manuscript-defined normalized DAILY
            # discomfort variance, inserted as an episodic terminal penalty
            # during collection. No raw-action dispersion proxy remains.
            actor_loss = (alpha_h * h_logp_sum - q_pi).mean()
            total_actor_loss = actor_loss

            self.household_opt.zero_grad()
            total_actor_loss.backward()
            self.household_opt.step()

            alpha_loss = -(self.log_alpha_h * (h_logp_sum.detach() + self.target_entropy_h)).mean()
            self.alpha_opt.zero_grad()
            alpha_loss.backward()
            self.alpha_opt.step()

            losses.update({"household_actor_loss": float(actor_loss.item()),
                            "household_alpha_loss": float(alpha_loss.item())})

        self.train_step_count += 1
        for k, v in losses.items():
            if k == "updated":
                continue
            if not np.isfinite(v):
                raise FloatingPointError(f"non-finite loss detected: {k}={v} at train_step {self.train_step_count}")
        return losses

    def save_checkpoint(self, path: str):
        """Saves EVERY piece of trainable/stateful information needed to
        resume exactly where training left off -- an earlier version
        omitted the entropy/zeta optimizers, the replay buffer, episode-
        loss history, step counters, and RNG state, so a 'resumed' run
        would silently restart entropy tuning from scratch and repeat
        already-seen random draws."""
        torch.save({
            "utility_actor": self.utility_actor.state_dict(),
            "household_actor": self.household_actor.state_dict(),
            "critic": self.critic.state_dict(),
            "critic_target": self.critic_target.state_dict(),
            "utility_opt": self.utility_opt.state_dict(),
            "household_opt": self.household_opt.state_dict(),
            "critic_opt": self.critic_opt.state_dict(),
            "alpha_opt": self.alpha_opt.state_dict(),
            "log_alpha_u": self.log_alpha_u.detach().clone(),
            "log_alpha_h": self.log_alpha_h.detach().clone(),
            "cvar_zeta": self.cvar_zeta,
            "daily_loss_history": self.daily_loss_history,
            "train_step_count": self.train_step_count,
            "env_step_count": self.env_step_count,
            "episode_losses": self.episode_losses,
            "buffer": self.buffer.state_dict(),
            "torch_rng_state": torch.get_rng_state(),
        }, path)

    def load_checkpoint(self, path: str):
        ckpt = torch.load(path, weights_only=False)
        self.utility_actor.load_state_dict(ckpt["utility_actor"])
        self.household_actor.load_state_dict(ckpt["household_actor"])
        self.critic.load_state_dict(ckpt["critic"])
        self.critic_target.load_state_dict(ckpt["critic_target"])
        self.utility_opt.load_state_dict(ckpt["utility_opt"])
        self.household_opt.load_state_dict(ckpt["household_opt"])
        self.critic_opt.load_state_dict(ckpt["critic_opt"])
        self.alpha_opt.load_state_dict(ckpt["alpha_opt"])
        with torch.no_grad():
            self.log_alpha_u.copy_(ckpt["log_alpha_u"])
            self.log_alpha_h.copy_(ckpt["log_alpha_h"])
        self.cvar_zeta = ckpt.get("cvar_zeta")
        self.daily_loss_history = ckpt.get("daily_loss_history", [])
        self.train_step_count = ckpt["train_step_count"]
        self.env_step_count = ckpt["env_step_count"]
        self.episode_losses = ckpt["episode_losses"]
        self.buffer.load_state_dict(ckpt["buffer"])
        torch.set_rng_state(ckpt["torch_rng_state"])
